      DBMS_SQL.NATIVE);
    DBMS_SQL.DESCRIBE_COLUMNS2(cursor_id, column_count, described_columns);
    IF column_count <> 1 OR NOT compatible(described_columns(1), 'TEXT') THEN
      fail('SIL_GET_CLIENT_NAME', 'expected a character return value');
    ELSE
      DBMS_OUTPUT.PUT_LINE('PASS FUNCTION_PARSE SIL_GET_CLIENT_NAME (body not executed)');
    END IF;
    DBMS_SQL.CLOSE_CURSOR(cursor_id);
  EXCEPTION WHEN OTHERS THEN
    IF cursor_id IS NOT NULL AND DBMS_SQL.IS_OPEN(cursor_id) THEN DBMS_SQL.CLOSE_CURSOR(cursor_id); END IF;
    fail('SIL_GET_CLIENT_NAME', 'resolution/function parse failed; SQLCODE=' || SQLCODE);
  END;
