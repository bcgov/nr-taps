  PROCEDURE fail(label VARCHAR2, detail VARCHAR2) IS
  BEGIN
    failures := failures + 1;
    DBMS_OUTPUT.PUT_LINE('FAIL ' || label || ': ' || detail);
  END;

  -- Resolve local/private/public synonyms without following a database link.
  -- Effective privileges are checked separately by parsing as this session's user.
  PROCEDURE resolve_local(object_name VARCHAR2, expected_type VARCHAR2) IS
    owner_name VARCHAR2(128) := SYS_CONTEXT('USERENV', 'CURRENT_SCHEMA');
    target_name VARCHAR2(128) := object_name;
    target_type VARCHAR2(30);
    target_status VARCHAR2(7);
    next_owner VARCHAR2(128);
    next_name VARCHAR2(128);
    link_name VARCHAR2(128);
  BEGIN
    FOR hop IN 1..16 LOOP
      BEGIN
        SELECT object_type, status INTO target_type, target_status
        FROM ALL_OBJECTS
        WHERE owner = owner_name AND object_name = target_name
          AND ((expected_type = 'RELATION' AND object_type IN ('TABLE', 'VIEW', 'MATERIALIZED VIEW'))
            OR (expected_type = 'FUNCTION' AND object_type = 'FUNCTION'))
          AND ROWNUM = 1;
        IF target_status <> 'VALID' THEN
          RAISE_APPLICATION_ERROR(-20002, 'Resolved object is not valid');
        END IF;
        DBMS_OUTPUT.PUT_LINE('RESOLVED ' || object_name || ' -> ' || owner_name || '.' || target_name || ' (' || target_type || ')');
        RETURN;
      EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
      END;
      BEGIN
        SELECT table_owner, table_name, db_link INTO next_owner, next_name, link_name
        FROM ALL_SYNONYMS WHERE owner = owner_name AND synonym_name = target_name;
      EXCEPTION WHEN NO_DATA_FOUND THEN
        IF hop = 1 THEN
          SELECT table_owner, table_name, db_link INTO next_owner, next_name, link_name
          FROM ALL_SYNONYMS WHERE owner = 'PUBLIC' AND synonym_name = target_name;
        ELSE
          RAISE_APPLICATION_ERROR(-20003, 'Unresolved local synonym target');
        END IF;
      END;
      IF link_name IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20004, 'Database-link resolution requires a separate approved review');
      END IF;
      owner_name := next_owner;
      target_name := next_name;
    END LOOP;
    RAISE_APPLICATION_ERROR(-20005, 'Synonym chain is cyclic or exceeds 16 hops');
  END;

  FUNCTION compatible(actual DBMS_SQL.DESC_REC2, expected VARCHAR2) RETURN BOOLEAN IS
  BEGIN
    IF expected = 'TEXT' THEN
      RETURN actual.col_type IN (1, 96); -- VARCHAR2/NVARCHAR2 or CHAR/NCHAR
    ELSIF expected = 'CLOB' THEN
      -- Oracle internal type 112; database-character-set CLOB, not NCLOB. Describe only.
      RETURN actual.col_type = 112 AND NVL(actual.col_charsetform, -1) = 1;
    ELSIF expected = 'NUMBER' THEN
      RETURN actual.col_type = 2;
    ELSIF expected = 'LOCAL_DATETIME' THEN
      RETURN actual.col_type IN (12, 180); -- DATE or TIMESTAMP, without timezone conversion
    ELSIF expected = 'MONEY_6_2' THEN
      RETURN actual.col_type = 2 AND NVL(actual.col_precision, -1) = 6 AND NVL(actual.col_scale, -1) = 2;
    ELSIF expected = 'MONEY_5_2' THEN
      RETURN actual.col_type = 2 AND NVL(actual.col_precision, -1) = 5 AND NVL(actual.col_scale, -1) = 2;
    END IF;
    RETURN FALSE;
  END;

  PROCEDURE check_table(object_name VARCHAR2, contract VARCHAR2) IS
    cursor_id INTEGER;
    column_count INTEGER;
    described_columns DBMS_SQL.DESC_TAB2;
    sql_text VARCHAR2(32767) := 'SELECT ';
    token VARCHAR2(256);
    expected VARCHAR2(30);
    column_name VARCHAR2(128);
    position PLS_INTEGER := 1;
    before_failures PLS_INTEGER := failures;
  BEGIN
    checked_objects := checked_objects + 1;
    resolve_local(object_name, 'RELATION');
    LOOP
      token := REGEXP_SUBSTR(contract, '[^,]+', 1, position);
      EXIT WHEN token IS NULL;
      column_name := SUBSTR(token, 1, INSTR(token, ':') - 1);
      IF position > 1 THEN sql_text := sql_text || ','; END IF;
      sql_text := sql_text || column_name;
      position := position + 1;
    END LOOP;
    sql_text := sql_text || ' FROM ' || object_name || ' WHERE 1 = 0';
    cursor_id := DBMS_SQL.OPEN_CURSOR;
    -- Parsing checks names and SELECT permission without running the query.
    DBMS_SQL.PARSE(cursor_id, sql_text, DBMS_SQL.NATIVE);
    DBMS_SQL.DESCRIBE_COLUMNS2(cursor_id, column_count, described_columns);
    IF column_count <> position - 1 THEN
      fail(object_name, 'column count differs from the query contract');
    END IF;
    FOR column_index IN 1..column_count LOOP
      token := REGEXP_SUBSTR(contract, '[^,]+', 1, column_index);
      column_name := SUBSTR(token, 1, INSTR(token, ':') - 1);
      expected := SUBSTR(token, INSTR(token, ':') + 1);
      checked_columns := checked_columns + 1;
      IF described_columns(column_index).col_name <> column_name
        OR NOT compatible(described_columns(column_index), expected) THEN
        fail(object_name || '.' || column_name, 'expected ' || expected
          || '; Oracle type=' || described_columns(column_index).col_type
          || ', precision=' || described_columns(column_index).col_precision
          || ', scale=' || described_columns(column_index).col_scale);
      END IF;
    END LOOP;
    DBMS_SQL.CLOSE_CURSOR(cursor_id);
    IF failures = before_failures THEN
      DBMS_OUTPUT.PUT_LINE('PASS SELECT_PARSE ' || object_name || ' (' || column_count || ' columns)');
    END IF;
  EXCEPTION WHEN OTHERS THEN
    IF cursor_id IS NOT NULL AND DBMS_SQL.IS_OPEN(cursor_id) THEN DBMS_SQL.CLOSE_CURSOR(cursor_id); END IF;
    fail(object_name, 'resolution/SELECT parse failed; SQLCODE=' || SQLCODE);
  END;

